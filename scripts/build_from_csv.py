def fetch_from_gsheet():
    """Fetch latest MASTER and SEATING from Google Sheets CSV export."""
    import requests
    base = f'https://docs.google.com/spreadsheets/d/{SHEET_ID}/export?format=csv'
    
    r_m = requests.get(f'{base}&gid={GID_MASTER}')
    r_m.encoding = 'utf-8'
    m_rows = list(csv.reader(io.StringIO(r_m.text)))
    m_list = []
    for r in m_rows[2:]:
        if len(r) > 1 and r[0].strip().isdigit() and r[1].strip():
            nm = r[1].strip()
            if nm.startswith('（範例）'):
                continue
            tb = r[2].strip() if len(r) > 2 else ''
            rel = r[3].strip() if len(r) > 3 else ''
            cake = r[6].strip() if len(r) > 6 else ''
            pax = r[7].strip() if len(r) > 7 else ''
            note = r[9].strip() if len(r) > 9 else ''
            m_list.append((nm, tb, rel, cake, pax, note))

    r_s = requests.get(f'{base}&gid={GID_SEATING}')
    r_s.encoding = 'utf-8'
    s_rows = list(csv.reader(io.StringIO(r_s.text)))
    s_list = []
    cur_t, cur_reg, cur_st = None, None, []
    hdr_re = re.compile(r'^\s*(.+?)\s*—\s*(.+)$')
    for r in s_rows:
        c0 = r[0].strip() if len(r) > 0 else ''
        c1 = r[1].strip() if len(r) > 1 else ''
        c2 = r[2].strip() if len(r) > 2 else ''
        c3 = r[3].strip() if len(r) > 3 else ''
        m = hdr_re.match(c0)
        if m:
            if cur_t:
                s_list.append((cur_t, cur_reg, cur_st))
            cur_t = m.group(1).strip()
            cur_reg = m.group(2).strip()
            cur_st = []
            continue
        if c0.isdigit():
            cur_st.append((int(c0), c1, c2, c3))
    if cur_t:
        s_list.append((cur_t, cur_reg, cur_st))
    return m_list, s_list

