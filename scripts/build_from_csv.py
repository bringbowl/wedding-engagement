def build_xlsx(master=None, seating=None, output_path='data/filled_from_gsheet.xlsx'):
    m_data = master or MASTER
    s_data = seating or SEATING

    wb = openpyxl.Workbook()
    # 賓客總表
    mw = wb.active
    mw.title = '賓客總表'
    hdr = ['序號', '姓名', '桌次', '關係／稱謂', '紅包金額', '報到', '喜餅', '報名人數', '實到人數', '備註']
    mw.append([])  # row1 (merged title placeholder)
    mw.append(hdr)  # row2 header
    mw.append([1, '（範例）王小明', '獅子王', '男方－大伯', 3600, '✓', '已領取', '', '', '吃素，需素食餐'])  # row3 example
    for i, (nm, tb, rel, cake, pax, note) in enumerate(m_data, start=1):
        paxv = int(pax) if pax else None
        mw.append([i, nm, tb, rel, None, None, cake or None, paxv, None, note or None])

    # 依桌次
    sw = wb.create_sheet('依桌次')
    sw.append(['依桌次　｜　排桌・桌卡・帶位用'])
    sw.append([])
    for name, region, seats in s_data:
        sw.append([f'　{name}　—　{region}'])
        sw.append(['座位', '姓名', '關係／稱謂', '備註'])
        used = 0
        for s, nm, rel, note in seats:
            sw.append([s, nm or None, rel or None, note or None])
            if nm or rel:
                used += 1
        sw.append([f'　本桌（總表已分配）：{used} 人'])
        sw.append([])

    wb.save(output_path)
    print(f'rebuilt xlsx: master {len(m_data)} tables {len(s_data)}')

